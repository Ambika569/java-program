package com.tech.operators;

public class unary {
    public static void main(String[] args){
        int a=9;
        System.out.println("program start here");
        System.out.println(a); //10 9
        System.out.println(a++); //10 9
        System.out.println(++a); //1211
        System.out.println(a--); //12 11
        System.out.println(--a); //10 9
        System.out.println("program end here");
    }
}
